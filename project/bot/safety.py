# Антиспам: скользящее окно на пользователя (в памяти процесса)
# ---------------------------------------------------------------------------
class RateLimiter:
    """Не больше `max_events` событий за `window_seconds` на пользователя."""

    def __init__(self, max_events: int, window_seconds: float,
                 clock: Callable[[], float] = time.monotonic) -> None:
        if max_events < 1 or window_seconds <= 0:
            raise ValueError("max_events >= 1 и window_seconds > 0")
        self.max_events = max_events
        self.window = window_seconds
        self._clock = clock
        self._events: dict[int, deque[float]] = defaultdict(deque)

    def allow(self, user_id: int) -> bool:
        now = self._clock()
        q = self._events[user_id]
        while q and now - q[0] >= self.window:
            q.popleft()
        if len(q) >= self.max_events:
            return False
        q.append(now)
        return True

    def forget(self, user_id: int) -> None:
        self._events.pop(user_id, None)


class Cooldown:
    """Помнит, когда для пользователя последний раз что-то происходило.

    Используется, чтобы: (1) не продавать пользователю после кризисного сообщения
    в течение `seconds`; (2) не заваливать владелицу одинаковыми уведомлениями.
    """

    def __init__(self, seconds: float, clock: Callable[[], float] = time.monotonic) -> None:
        self.seconds = seconds
        self._clock = clock
        self._last: dict[int, float] = {}

    def mark(self, user_id: int) -> None:
        self._last[user_id] = self._clock()

    def active(self, user_id: int) -> bool:
        t = self._last.get(user_id)
        return t is not None and self._clock() - t < self.seconds

    def forget(self, user_id: int) -> None:
        self._last.pop(user_id, None)
