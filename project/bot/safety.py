def is_too_long(text: str, limit: int) -> bool:
    return len(text or "") > limit


def truncate(text: str, limit: int, suffix: str = "…") -> str:
    if len(text) <= limit:
        return text
    return text[: max(0, limit - len(suffix))].rstrip() + suffix


