# Порядок важен: «бл…, верните деньги» — это возврат, а не только мат.
INTENT_ORDER = ("refund", "file_missing", "nofit", "complaint", "human", "profanity")
_INTENTS_COMPILED = {k: [re.compile(p) for p in v] for k, v in _INTENTS.items()}


@dataclass(frozen=True)
class IntentResult:
    intent: str | None = None     # refund | file_missing | nofit | complaint | human | profanity
    matched: str | None = None

    @property
    def found(self) -> bool:
        return self.intent is not None


def detect_intent(text: str, only: tuple[str, ...] | None = None) -> IntentResult:
    if not text:
        return IntentResult()
    vs = variants(text)
    for intent in INTENT_ORDER:
        if only is not None and intent not in only:
            continue
        for v in vs:
            for rx in _INTENTS_COMPILED[intent]:
                m = rx.search(v)
                if m:
                    return IntentResult(intent, m.group(0))
    return IntentResult()


